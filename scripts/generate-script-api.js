#!/usr/bin/env node
const fs = require('fs');
const os = require('os');
const path = require('path');
const ts = require('typescript');

/**
 * generate-script-api.js
 *
 * Usage:
 *   node scripts/generate-script-api.js [--check]
 *
 * Description:
 *   Walks the script API outward from the globals declared in
 *   packages/bruno-js/types/globals.d.ts, reading types and docs from the
 *   JSDoc on the bruno-js classes, and writes:
 *   - packages/bruno-js/types/script-api.d.ts: one flattened interface per
 *     public type, the input of the API reference site
 *   - packages/bruno-app/src/utils/codemirror/generated/script-api-manifest.json:
 *     one entry per member path, for editor autocomplete and hover
 *   Both come from the same walk, so they cannot disagree.
 *
 *   tsc's own declaration emit is not used: for JS input it drops subclass
 *   overrides whose type matches the base (losing their docs), leaks private
 *   methods and keeps internal base classes in the hierarchy.
 *
 * Options:
 *   --check   Fail instead of writing when either output is out of date
 */

const ROOT = path.resolve(__dirname, '..');
const JS_PKG = path.join(ROOT, 'packages', 'bruno-js');
const TSCONFIG = path.join(JS_PKG, 'tsconfig.script-api.json');
const GLOBALS = path.join(JS_PKG, 'types', 'globals.d.ts');
const DTS_OUT = path.join(JS_PKG, 'types', 'script-api.d.ts');
const MANIFEST_OUT = path.join(ROOT, 'packages', 'bruno-app', 'src', 'utils', 'codemirror', 'generated', 'script-api-manifest.json');

// The compiler reports file names with forward slashes on every platform.
const toPosix = (p) => p.split(path.sep).join('/');
// Windows paths are case-insensitive, and the drive letter's case varies between APIs.
const comparablePath = (p) => (process.platform === 'win32' ? p.toLowerCase() : p);
const JS_PKG_POSIX = comparablePath(toPosix(JS_PKG) + '/');

const CONTEXTS = [
  'pre-request',
  'post-response',
  'tests',
  'grpc:before-call-start',
  'grpc:before-message-send',
  'grpc:after-message-receive',
  'grpc:after-call-end'
];
const RUNTIMES = ['nodevm', 'quickjs'];

// Tags that only shape the TypeScript types; the emitted signatures already say what they say.
const TYPING_TAGS = new Set(['type', 'template', 'extends', 'augments', 'typedef', 'callback', 'property', 'prop', 'internal', 'protected', 'readonly']);

const HEADER = '// Generated by scripts/generate-script-api.js from the JSDoc in packages/bruno-js. Do not edit.';

const fail = (message) => {
  throw new Error(`generate-script-api: ${message}`);
};

const diagnosticHost = {
  getCanonicalFileName: (f) => f,
  getCurrentDirectory: () => ROOT,
  getNewLine: () => '\n'
};

const assertNoDiagnostics = (diagnostics, what) => {
  if (diagnostics.length) {
    fail(`${what} does not compile:\n${ts.formatDiagnostics(diagnostics, diagnosticHost)}`);
  }
};

const loadProgram = () => {
  const config = ts.getParsedCommandLineOfConfigFile(TSCONFIG, {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => assertNoDiagnostics([d], TSCONFIG)
  });
  assertNoDiagnostics(config.errors, TSCONFIG);
  const program = ts.createProgram(config.fileNames, config.options);
  // Only globals.d.ts itself is checked: the JS sources pull in third-party typings that are no
  // concern of the script API.
  const globals = program.getSourceFile(toPosix(GLOBALS));
  assertNoDiagnostics([
    ...program.getOptionsDiagnostics(),
    ...program.getSyntacticDiagnostics(globals),
    ...program.getSemanticDiagnostics(globals)
  ], 'globals.d.ts');
  return program;
};

const createGenerator = (program) => {
  const checker = program.getTypeChecker();
  const typeLibraries = new Set();
  // symbol -> { name, symbol, type }, in discovery order
  const publicTypes = new Map();
  const namesInUse = new Map();
  const pending = [];
  // The `@category` of the global or type being walked. A type the walk discovers is filed under
  // it in the API reference's navigation, unless it names its own `@category`.
  let currentHome = null;

  // ── Where a declaration comes from ───────────────────────────────────

  const isOwnDeclaration = (decl) => {
    const file = comparablePath(decl.getSourceFile().fileName);
    return file.startsWith(JS_PKG_POSIX) && !file.includes('/node_modules/');
  };

  const libraryOf = (decl) => {
    const sourceFile = decl.getSourceFile();
    if (program.isSourceFileDefaultLibrary(sourceFile)) return 'lib';
    const match = sourceFile.fileName.match(/\/node_modules\/@types\/([^/]+)\//);
    return match ? match[1] : null;
  };

  const locationOf = (decl) => {
    const sourceFile = decl.getSourceFile();
    const { line } = sourceFile.getLineAndCharacterOfPosition(decl.getStart());
    return `${path.relative(ROOT, sourceFile.fileName)}:${line + 1}`;
  };

  /** 'own' (expanded into the output), 'library' (referenced by name) or a failure. */
  const originOf = (symbol, where) => {
    const decls = symbol.declarations || [];
    if (decls.length && decls.every(isOwnDeclaration)) return 'own';
    const library = decls.map(libraryOf).find(Boolean);
    if (library) {
      if (library !== 'lib') typeLibraries.add(library);
      return 'library';
    }
    const from = decls.length ? locationOf(decls[0]) : 'an unknown file';
    fail(`${where}: type ${symbol.name} comes from ${from}; describe it with a JSDoc @typedef in bruno-js`);
  };

  // ── Docs ─────────────────────────────────────────────────────────────

  // Sources checked out with CRLF must produce the same output as LF ones.
  const partsToString = (parts) => ts.displayPartsToString(parts || []).replace(/\r\n?/g, '\n').trim();

  const oneLine = (text) => text.replace(/\s*\n\s*/g, ' ');

  /** Reads the JSDoc of a symbol or a signature. */
  const readDoc = (source) => {
    // A typedef `@property`'s comment keeps the `- ` that separates it from the name, as `@param` and `@returns` text does.
    const text = partsToString(source.getDocumentationComment(checker)).replace(/^-\s+/, '');
    const [summary = '', ...rest] = text.split(/\n\s*\n/);
    const doc = {
      text,
      summary: oneLine(summary).trim(),
      description: rest.join('\n\n').trim(),
      tags: [],
      params: new Map(),
      returns: '',
      examples: [],
      category: null,
      contexts: null,
      runtimes: null,
      internal: false,
      protected: false
    };

    for (const tag of source.getJsDocTags(checker)) {
      const parts = tag.text || [];
      if (tag.name === 'param') {
        const name = parts.find((p) => p.kind === 'parameterName')?.text;
        const description = oneLine(partsToString(parts.filter((p) => p.kind !== 'parameterName'))).replace(/^-\s*/, '');
        if (name && !doc.params.has(name)) doc.params.set(name, description);
        continue;
      }
      const tagText = partsToString(parts);
      if (tag.name === 'returns' || tag.name === 'return') doc.returns = oneLine(tagText).replace(/^-\s*/, '');
      if (tag.name === 'example') doc.examples.push(tagText);
      if (tag.name === 'category') doc.category = tagText;
      if (tag.name === 'internal') doc.internal = true;
      if (tag.name === 'protected' || tag.name === 'private') doc.protected = true;
      if (tag.name === 'context') doc.contexts = tagText.split(/\s+/).filter(Boolean);
      if (tag.name === 'runtime') doc.runtimes = tagText.split(/\s+/).filter(Boolean);
      doc.tags.push({ name: tag.name, text: tagText });
    }
    return doc;
  };

  const validateDoc = (doc, where, { requireCategory }) => {
    if (!doc.summary) fail(`${where} has no JSDoc summary (document it, or mark it @internal)`);
    if (requireCategory && !doc.category) fail(`${where} has no @category`);
    for (const context of doc.contexts || []) {
      if (!CONTEXTS.includes(context)) fail(`${where}: unknown @context "${context}" (expected one of ${CONTEXTS.join(', ')})`);
    }
    for (const runtime of doc.runtimes || []) {
      if (!RUNTIMES.includes(runtime)) fail(`${where}: unknown @runtime "${runtime}" (expected one of ${RUNTIMES.join(', ')})`);
    }
  };

  // ── Types ────────────────────────────────────────────────────────────

  const isErrorType = (type) => (type.flags & ts.TypeFlags.Any) !== 0 && type.intrinsicName === 'error';

  /** `(a) => b` for `((a) => b)`, but `(a) | (b)` stays as it is. */
  const unwrapParens = (text) => {
    if (!text.startsWith('(') || !text.endsWith(')')) return text;
    let depth = 0;
    for (let i = 0; i < text.length; i++) {
      if (text[i] === '(') depth++;
      if (text[i] === ')') depth--;
      if (depth === 0 && i < text.length - 1) return text;
    }
    return text.slice(1, -1);
  };

  const renderType = (type, { optional = false } = {}) => {
    const flags = ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope | ts.TypeFormatFlags.UseFullyQualifiedType;
    // Module-scoped typedefs print as `import("…").Name`; the output declares every name at top level.
    const text = checker.typeToString(type, undefined, flags).replace(/import\("[^"]*"\)\./g, '');
    // An optional parameter's type carries `| undefined`, which the `?` already says.
    return optional ? unwrapParens(text.replace(/ \| undefined$/, '')) : text;
  };

  const registerPublicType = (symbol, type, where) => {
    if (publicTypes.has(symbol)) return;
    const declared = checker.getDeclaredTypeOfSymbol(symbol);
    if (declared.typeParameters?.length || type.aliasTypeArguments?.length) {
      fail(`${where}: generic type ${symbol.name} is reachable from the script API; expose a concrete subclass or typedef`);
    }
    const existing = namesInUse.get(symbol.name);
    if (existing) {
      fail(`two public types are named ${symbol.name}: ${locationOf(existing.declarations[0])} and ${locationOf(symbol.declarations[0])}`);
    }
    namesInUse.set(symbol.name, symbol);
    const entry = { name: symbol.name, symbol, type, home: currentHome };
    publicTypes.set(symbol, entry);
    pending.push(entry);
  };

  /** Registers every public type `type` mentions; library types are only walked for their arguments. */
  const collectType = (type, where, seen = new Set()) => {
    if (seen.has(type)) return;
    seen.add(type);
    if (isErrorType(type)) fail(`${where}: unresolved type name in JSDoc`);

    if (type.aliasSymbol) {
      if (originOf(type.aliasSymbol, where) === 'own') {
        registerPublicType(type.aliasSymbol, type, where);
        return;
      }
      (type.aliasTypeArguments || []).forEach((t) => collectType(t, where, seen));
      return;
    }
    if (type.isUnionOrIntersection()) {
      type.types.forEach((t) => collectType(t, where, seen));
      return;
    }
    if (!(type.flags & ts.TypeFlags.Object)) return;

    if (type.objectFlags & ts.ObjectFlags.Reference) {
      checker.getTypeArguments(type).forEach((t) => collectType(t, where, seen));
    }
    const symbol = type.getSymbol();
    if (symbol && symbol.flags & (ts.SymbolFlags.Class | ts.SymbolFlags.Interface)) {
      if (originOf(symbol, where) === 'own') registerPublicType(symbol, checker.getDeclaredTypeOfSymbol(symbol), where);
      return;
    }
    // An anonymous object or function type is printed inline, so whatever it mentions is walked.
    for (const signature of checker.getSignaturesOfType(type, ts.SignatureKind.Call)) {
      signature.parameters.forEach((p) => collectType(checker.getTypeOfSymbol(p), `${where}(${p.name})`, seen));
      collectType(checker.getReturnTypeOfSignature(signature), `${where}()`, seen);
    }
    for (const property of checker.getPropertiesOfType(type)) {
      collectType(checker.getTypeOfSymbol(property), `${where}.${property.name}`, seen);
    }
  };

  /** The registered public interface a property's type points at, if any. */
  const publicInterfaceOf = (type) => {
    const nonNullable = checker.getNonNullableType(type);
    const key = nonNullable.aliasSymbol || nonNullable.getSymbol();
    const entry = key && publicTypes.get(key);
    return entry && describeType(entry).shape === 'interface' ? entry : null;
  };

  // ── Signatures and members ───────────────────────────────────────────

  const isJsDeclaration = (decl) => /\.js$/.test(decl.getSourceFile().fileName);

  /** In JS an untyped parameter silently becomes `any`, so every parameter must be typed. */
  const assertParameterTyped = (decl, where) => {
    if (!decl || !ts.isParameter(decl) || !isJsDeclaration(decl)) return;
    const host = decl.parent;
    if (!ts.isFunctionLike(host) || ts.isJSDocFunctionType(host) || ts.isFunctionTypeNode(host)) return;
    if (ts.getJSDocType(decl)) return;
    // A method typed as a whole with `@type {(…) => …}` types its parameters there.
    const typed = [host, host.parent].some((node) => node && ts.getJSDocTypeTag(node));
    if (!typed) fail(`${where}: parameter "${decl.name.getText()}" has no JSDoc type`);
  };

  /** A JS method with a body must state its return type unless it returns nothing. */
  const assertReturnTyped = (signature, where) => {
    const decl = signature.getDeclaration();
    if (!decl || !isJsDeclaration(decl) || !decl.body) return;
    if (ts.getJSDocReturnType(decl) || ts.getJSDocTypeTag(decl) || (decl.parent && ts.getJSDocTypeTag(decl.parent))) return;
    const returnType = checker.getReturnTypeOfSignature(signature);
    if (!(returnType.flags & ts.TypeFlags.Void)) fail(`${where} has no @returns type`);
  };

  const describeSignature = (signature, memberDoc, where) => {
    assertReturnTyped(signature, where);
    // A call signature declared in an interface carries its own JSDoc; a method's lives on its symbol.
    const signatureDoc = readDoc(signature);
    const paramDescription = (name) => memberDoc.params.get(name) || signatureDoc.params.get(name) || '';
    const params = signature.parameters.map((param, index) => {
      const decl = param.valueDeclaration;
      if (param.name.startsWith('__')) fail(`${where}: name the destructured parameter so it can be documented`);
      assertParameterTyped(decl, where);
      const rest = Boolean(decl && ts.isParameter(decl) && decl.dotDotDotToken);
      const optional = !rest && index >= signature.minArgumentCount;
      const type = checker.getTypeOfSymbol(param);
      collectType(type, `${where}(${param.name})`);
      return {
        name: param.name,
        type: renderType(type, { optional }),
        optional,
        rest,
        description: paramDescription(param.name)
      };
    });
    const returnType = checker.getReturnTypeOfSignature(signature);
    collectType(returnType, `${where}()`);
    const paramList = params
      .map((p) => `${p.rest ? '...' : ''}${p.name}${p.optional ? '?' : ''}: ${p.type}`)
      .join(', ');
    const returns = { type: renderType(returnType), description: memberDoc.returns || signatureDoc.returns };
    return { params, returns, doc: signatureDoc, text: `(${paramList}): ${returns.type}` };
  };

  const hiddenByModifier = (symbol) => (symbol.declarations || []).some(
    (decl) => ts.getCombinedModifierFlags(decl) & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected)
  );

  const isTypedefProperty = (symbol) => (symbol.declarations || []).every((decl) => ts.isJSDocPropertyLikeTag(decl));

  const isReadonly = (symbol) => (symbol.declarations || []).some(
    (decl) => ts.getCombinedModifierFlags(decl) & ts.ModifierFlags.Readonly
  );

  const describeMembers = (type, owner) => {
    const members = [];
    for (const symbol of checker.getPropertiesOfType(type)) {
      const name = symbol.name;
      // `#private` members surface as `#name` (or `__#…` in older compilers); well-known symbols as `__@…`.
      if (name.startsWith('#') || name.startsWith('__#') || name.startsWith('__@')) continue;
      const where = `${owner}.${name}`;
      const doc = readDoc(symbol);
      if (doc.internal || doc.protected || hiddenByModifier(symbol)) continue;
      if (name.startsWith('_')) fail(`${where} looks private; mark it @internal or @protected`);

      // A typedef's `@property` can't carry tags; its members take the category of what holds them.
      validateDoc(doc, where, { requireCategory: !isTypedefProperty(symbol) });

      const optional = Boolean(symbol.flags & ts.SymbolFlags.Optional);
      const memberType = checker.getTypeOfSymbol(symbol);
      const signatures = checker.getSignaturesOfType(checker.getNonNullableType(memberType), ts.SignatureKind.Call);
      const isMethod = signatures.length > 0 && checker.getPropertiesOfType(memberType).length === 0;

      if (isMethod) {
        members.push({
          name,
          kind: 'method',
          doc,
          signatures: signatures.map((s) => describeSignature(s, doc, where))
        });
      } else {
        collectType(memberType, where);
        members.push({
          name,
          kind: 'property',
          doc,
          optional,
          readonly: isReadonly(symbol),
          type: memberType,
          typeText: renderType(memberType, { optional })
        });
      }
    }
    return members;
  };

  const describedTypes = new Map();

  const describeType = (entry) => {
    if (describedTypes.has(entry)) return describedTypes.get(entry);
    const { symbol, type, name } = entry;
    const doc = readDoc(symbol);
    validateDoc(doc, name, { requireCategory: false });
    if (!doc.category) {
      doc.category = entry.home;
      doc.tags.push({ name: 'category', text: entry.home });
    }
    const outerHome = currentHome;
    currentHome = doc.category;
    const isObject = (type.flags & ts.TypeFlags.Object) !== 0;
    const properties = isObject ? checker.getPropertiesOfType(type) : [];
    const callSignatures = isObject ? checker.getSignaturesOfType(type, ts.SignatureKind.Call) : [];
    let described;
    if (isObject && (properties.length || !callSignatures.length)) {
      described = {
        shape: 'interface',
        doc,
        members: [],
        callSignatures: []
      };
      describedTypes.set(entry, described);
      described.members = describeMembers(type, name);
      described.callSignatures = callSignatures.map((s) => describeSignature(s, doc, name));
    } else {
      collectType(type, name);
      described = {
        shape: 'alias',
        doc,
        text: renderType(type)
      };
      describedTypes.set(entry, described);
    }
    currentHome = outerHome;
    return described;
  };

  // ── Globals ──────────────────────────────────────────────────────────

  const readGlobals = () => {
    const sourceFile = program.getSourceFile(toPosix(GLOBALS));
    const moduleSymbol = checker.getSymbolAtLocation(sourceFile);
    // A module .d.ts exports every top-level declaration; only the values are script globals.
    const position = (symbol) => symbol.declarations[0].getStart();
    return checker.getExportsOfModule(moduleSymbol)
      .filter((symbol) => symbol.flags & (ts.SymbolFlags.Variable | ts.SymbolFlags.Function))
      .sort((a, b) => position(a) - position(b))
      .map((symbol) => {
        const doc = readDoc(symbol);
        validateDoc(doc, symbol.name, { requireCategory: true });
        if (!doc.contexts) fail(`global ${symbol.name} has no @context`);
        const type = checker.getTypeOfSymbol(symbol);
        currentHome = doc.category;
        collectType(type, symbol.name);
        const signatures = checker.getSignaturesOfType(type, ts.SignatureKind.Call);
        return {
          name: symbol.name,
          doc,
          type,
          isFunction: Boolean(symbol.flags & ts.SymbolFlags.Function),
          signatures: signatures.map((s) => describeSignature(s, doc, symbol.name))
        };
      });
  };

  // ── Rendering: script-api.d.ts ───────────────────────────────────────

  const jsdoc = (doc, indent, { params = [], returns = null } = {}) => {
    const lines = doc.text ? doc.text.split('\n') : [];
    const tagLines = [];
    for (const param of params) {
      if (param.description) tagLines.push(`@param ${param.name} - ${param.description}`);
    }
    if (returns && returns.description) tagLines.push(`@returns ${returns.description}`);
    for (const tag of doc.tags) {
      if (TYPING_TAGS.has(tag.name) || tag.name === 'returns' || tag.name === 'return') continue;
      if (tag.name === 'example') {
        tagLines.push('@example', ...tag.text.split('\n'));
      } else {
        tagLines.push(tag.text ? `@${tag.name} ${tag.text}` : `@${tag.name}`);
      }
    }
    if (lines.length && tagLines.length) lines.push('');
    lines.push(...tagLines);
    if (!lines.length) return [];
    const escaped = lines.flatMap((line) => line.split('\n')).map((line) => line.replace(/\*\//g, '*\\/'));
    return [`${indent}/**`, ...escaped.map((line) => (line ? `${indent} * ${line}` : `${indent} *`)), `${indent} */`];
  };

  const renderMember = (member, indent) => {
    if (member.kind === 'method') {
      return member.signatures.flatMap((signature) => [
        ...jsdoc(member.doc, indent, signature),
        `${indent}${member.name}${signature.text};`
      ]);
    }
    const modifier = member.readonly ? 'readonly ' : '';
    return [...jsdoc(member.doc, indent), `${indent}${modifier}${member.name}${member.optional ? '?' : ''}: ${member.typeText};`];
  };

  const renderDeclarations = (globals) => {
    const out = [HEADER];
    for (const library of [...typeLibraries].sort()) out.push(`/// <reference types="${library}" />`);
    out.push('');

    for (const global of globals) {
      if (global.isFunction) {
        for (const signature of global.signatures) {
          out.push(...jsdoc(global.doc, '', signature));
          out.push(`export declare function ${global.name}${signature.text};`, '');
        }
      } else {
        out.push(...jsdoc(global.doc, ''), `export declare const ${global.name}: ${renderType(global.type)};`, '');
      }
    }

    for (const entry of publicTypes.values()) {
      const described = describeType(entry);
      out.push(...jsdoc(described.doc, ''));
      if (described.shape === 'alias') {
        out.push(`export type ${entry.name} = ${described.text};`, '');
        continue;
      }
      out.push(`export interface ${entry.name} {`);
      for (const signature of described.callSignatures) {
        out.push(...jsdoc(signature.doc, '  ', signature), `  ${signature.text};`);
      }
      for (const member of described.members) out.push(...renderMember(member, '  '));
      out.push('}', '');
    }
    return out.join('\n').replace(/\n+$/, '\n');
  };

  // ── Rendering: the editor manifest ───────────────────────────────────

  const intersect = (inherited, own) => (own ? inherited.filter((value) => own.includes(value)) : inherited);

  const manifestEntry = (path, kind, doc, signatureText, scope, signature) => ({
    path,
    kind,
    signature: signatureText,
    summary: doc.summary,
    description: doc.description,
    examples: doc.examples,
    category: scope.category,
    params: signature ? signature.params : [],
    returns: signature ? signature.returns : null,
    contexts: scope.contexts,
    runtimes: scope.runtimes
  });

  const walkMembers = (entries, prefix, typeEntry, inherited, ancestors) => {
    for (const member of describeType(typeEntry).members) {
      const path = `${prefix}.${member.name}`;
      const scope = {
        contexts: intersect(inherited.contexts, member.doc.contexts),
        runtimes: intersect(inherited.runtimes, member.doc.runtimes),
        category: member.doc.category || inherited.category
      };
      if (!scope.contexts.length) fail(`${path}: its @context leaves it available in no script context`);
      if (member.kind === 'method') {
        for (const signature of member.signatures) {
          entries.push(manifestEntry(path, 'method', member.doc, `${member.name}${signature.text}`, scope, signature));
        }
        continue;
      }
      entries.push(manifestEntry(path, 'property', member.doc, `${member.name}: ${member.typeText}`, scope, null));
      const target = publicInterfaceOf(member.type);
      if (target && !ancestors.includes(target)) {
        walkMembers(entries, path, target, scope, [...ancestors, target]);
      }
    }
  };

  const buildManifest = (globals) => {
    const entries = [];
    for (const global of globals) {
      const scope = {
        contexts: global.doc.contexts,
        runtimes: global.doc.runtimes || RUNTIMES,
        category: global.doc.category
      };
      if (global.signatures.length) {
        for (const signature of global.signatures) {
          entries.push(manifestEntry(global.name, 'global', global.doc, `${global.name}${signature.text}`, scope, signature));
        }
      } else {
        entries.push(manifestEntry(global.name, 'global', global.doc, `${global.name}: ${renderType(global.type)}`, scope, null));
      }
      const target = publicInterfaceOf(global.type);
      if (target) walkMembers(entries, global.name, target, scope, [target]);
    }
    return entries;
  };

  // ── Run ──────────────────────────────────────────────────────────────

  const generate = () => {
    const globals = readGlobals();
    // Describing a type can discover more, so drain until nothing new turns up.
    while (pending.length) describeType(pending.shift());
    const manifest = buildManifest(globals);
    return {
      declarations: renderDeclarations(globals),
      manifest: JSON.stringify(manifest, null, 2) + '\n'
    };
  };

  return { generate };
};

/** The emitted declarations must stand on their own, with no access to the JS sources. */
const assertDeclarationsCompile = (declarations) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'script-api-'));
  const file = path.join(dir, 'script-api.d.ts');
  try {
    fs.writeFileSync(file, declarations);
    const { options, errors } = ts.convertCompilerOptionsFromJson({
      strict: true,
      noEmit: true,
      lib: ['es2022'],
      types: [],
      typeRoots: [path.join(ROOT, 'node_modules', '@types')]
    }, dir);
    assertNoDiagnostics(errors, 'compiler options');
    const program = ts.createProgram([file], options);
    assertNoDiagnostics(ts.getPreEmitDiagnostics(program), 'the generated script-api.d.ts');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true, maxRetries: 3, retryDelay: 100 });
  }
};

const main = () => {
  const check = process.argv.includes('--check');
  const program = loadProgram();
  const { declarations, manifest } = createGenerator(program).generate();
  assertDeclarationsCompile(declarations);

  const outputs = [
    [DTS_OUT, declarations],
    [MANIFEST_OUT, manifest]
  ];

  if (check) {
    const stale = outputs.filter(([file, content]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content);
    if (stale.length) {
      console.error(`Script API outputs are out of date:\n${stale.map(([file]) => `  ${path.relative(ROOT, file)}`).join('\n')}`);
      console.error('Run `npm run generate:script-api` and commit the result.');
      process.exit(1);
    }
    console.log('Script API outputs are up to date.');
    return;
  }

  for (const [file, content] of outputs) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    console.log(`Wrote ${path.relative(ROOT, file)}`);
  }
};

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
